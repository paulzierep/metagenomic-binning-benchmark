#!/usr/bin/env python3
"""rank_sweep_medium.py — rank finished issue-#25 sweep cells.

Reads every `results/sweep_*.csv` (auto-generated by run_eval.sh) plus the
per-cell sweep meta from `runs/<cell>/run_meta.txt` (`sweep:` line, seed,
wall time) and ranks them with the owner's rule (docs/13):

  1. Bin stats first: CheckM2 mean completeness / contamination, HQ + MQ
     counts, then CheckM v1; F1 = 2*c*p/(c+p), p = 100 - contamination.
  2. Runtime tiebreak: if bin stats are within ~±1 pt, the shorter wall time
     wins.
  3. Output: ranked markdown table (results/sweep_rankings.md) — printed too.

Only completed cells (results CSV present) are ranked; missing coordinates in
the meta default to "ref"; a `wall_s` from run_meta is used when the CSV has no
total_time_s. Cells without a results CSV are listed separately as pending.

Usage (inside the comebin env for nothing special — stdlib only):
    python3 scripts/rank_sweep_medium.py
"""

import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get("BENCH_REPO", os.path.normpath(os.path.join(HERE, "..")))
RESULTS = os.path.join(REPO, "results")
RUNS = os.path.join(REPO, "runs")
OUT = os.path.join(RESULTS, "sweep_rankings.md")

AXES = ["temp", "emb", "emb_cov", "batch", "max_edges",
        "leiden_workers", "hmm_evalue", "n_views"]


def read_meta(cell):
    """Parse run_meta.txt -> dict of the sweep/seed/wall/cmd fields."""
    meta = {}
    path = os.path.join(RUNS, cell, "run_meta.txt")
    if not os.path.isfile(path):
        return meta
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("sweep:"):
                for tok in line.split(":", 1)[1].split():
                    if "=" in tok:
                        k, v = tok.split("=", 1)
                        meta.setdefault(k, v)
            elif line.startswith("seed:"):
                meta["seed"] = line.split(":", 1)[1].strip()
            elif line.startswith("wall_s:"):
                meta["wall_s"] = line.split(":", 1)[1].strip()
            elif line.startswith("cmd_wrapper:"):
                meta["cmd"] = line.split(":", 1)[1].strip()
    return meta


# run_comebin.sh CLI flag -> sweep axis, as forwarded by run_comebin_fix.sh.
FLAG_AXES = {
    "-l": "temp",       # COMEBIN_TEMPERATURE (never TEMP: libmamba reads TEMP
    "-e": "emb",        # as a temp-dir path, which aborted the temp cells)
    "-c": "emb_cov",
    "-b": "batch",
    "-m": "max_edges",
    "-w": "leiden_workers",
    "-E": "hmm_evalue",
    "-n": "n_views",
}


def parse_cmd_axes(cmd):
    """Extract the actually-applied sweep axes from a `cmd_wrapper:` line.

    This is the authoritative record of what COMEBin received: the `sweep:`
    meta line is written by the driver and went stale for the temperature cells
    (sweep_004/005/006 recorded `temp=ref` even though `-l 0.05/0.30/0.50` was
    passed and the run log confirms `Tau(temperature): 0.05/0.30/0.50`).
    """
    axes = {}
    if not cmd:
        return axes
    toks = cmd.split()
    for i, tok in enumerate(toks):
        axis = FLAG_AXES.get(tok)
        if axis and i + 1 < len(toks):
            axes[axis] = toks[i + 1]
    return axes


def resolve_axes(cell, meta):
    """Applied axes from cmd_wrapper, cross-checked against the `sweep:` line.

    Returns (axes, mismatches). `cmd_wrapper` wins; a `sweep:` value that
    disagrees is reported so the doc can call the metadata bug out instead of
    silently ranking a cell under the wrong coordinates.
    """
    cmd_axes = parse_cmd_axes(meta.get("cmd", ""))
    axes = dict(cmd_axes)
    mismatches = []
    for axis in AXES:
        declared = meta.get(axis, "ref")
        applied = cmd_axes.get(axis)
        if declared in (None, "ref"):
            continue
        if applied is None or applied == "ref":
            # run_meta declares a value the command line does not carry.
            axes.setdefault(axis, declared)
            if applied is None:
                mismatches.append(f"{axis}: meta={declared}, not in cmd")
        elif applied != declared and not (
            axis == "n_views" and (declared, applied) == ("6", "6")
        ):
            mismatches.append(f"{axis}: meta={declared}, cmd={applied}")
            axes[axis] = applied
    # n_views is always explicit (-n); the reference grid value is 6.
    if axes.get("n_views") == "6":
        axes["n_views"] = "ref"
    return axes, mismatches


def coord_str(axes):
    """'temp=ref emb=ref ...' but only the axes — matches docs/13 grid."""
    return " ".join(f"{ax}={axes.get(ax, 'ref')}" for ax in AXES)


def f1(comp, cont):
    """Harmonic mean of completeness and purity, or None when not computable."""
    try:
        comp = float(comp)
        p = 100.0 - float(cont)
    except (TypeError, ValueError):
        return None
    if comp != comp or p != p:  # NaN inputs
        return None
    if comp + p <= 0:
        return 0.0
    return 2 * comp * p / (comp + p)


def fmt_f1(value):
    return "-" if value is None else f"{value:.2f}"


def main():
    cells = []
    if os.path.isdir(RESULTS):
        for fn in sorted(os.listdir(RESULTS)):
            if not (fn.startswith("sweep_") and fn.endswith(".csv")):
                continue
            cell = fn[:-4]
            with open(os.path.join(RESULTS, fn), encoding="utf-8") as f:
                row = next(csv.DictReader(f), None)
            if not row:
                continue
            meta = read_meta(cell)
            axes, mismatches = resolve_axes(cell, meta)
            wall = row.get("total_time_s") or meta.get("wall_s") or "-"
            cells.append({
                "cell": cell,
                "commit": (row.get("source_commit") or "-")[:7],
                "seed": meta.get("seed", "-"),
                "params": coord_str(axes),
                "mismatches": mismatches,
                "wall": wall,
                "n_bins": row.get("n_bins", "-"),
                "c2c": row.get("checkm2_mean_completeness", "-"),
                "c2n": row.get("checkm2_mean_contamination", "-"),
                "hq2": row.get("checkm2_HQ", "-"),
                "mq2": row.get("checkm2_MQ", "-"),
                "c1c": row.get("checkm_mean_completeness", "-"),
                "c1n": row.get("checkm_mean_contamination", "-"),
                "f1": f1(row.get("checkm2_mean_completeness"),
                         row.get("checkm2_mean_contamination")),
            })

    def wall_s(v):
        try:
            return int(float(v))
        except (TypeError, ValueError):
            return float("inf")

    def as_int(v):
        try:
            return int(float(v))
        except (TypeError, ValueError):
            return 0

    def as_float(v, default):
        try:
            x = float(v)
            return x if x == x else default  # NaN -> default
        except (TypeError, ValueError):
            return default

    # Rank: CheckM2 comp (desc), cont (asc), HQ+MQ (desc), F1 (desc), wall (asc).
    cells.sort(key=lambda c: (
        -as_float(c["c2c"], -1.0),
        as_float(c["c2n"], 1e9),
        -(as_int(c["hq2"]) + as_int(c["mq2"])),
        -as_float(c["f1"], float("-inf")),
        wall_s(c["wall"]),
        c["cell"],
    ))

    lines = [
        "| Rank | Cell | Commit | Seed | Params (non-ref) | Wall | Bins "
        "| CheckM2 comp | CheckM2 cont | HQ / MQ | F1 | CheckM1 comp / cont |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, c in enumerate(cells, 1):
        nonref = " ".join(
            p for p in c["params"].split()
            if not p.endswith("=ref")) or "reference (defaults)"
        lines.append(
            "| {rank} | `{cell}` | `{commit}` | {seed} | {params} | {wall} "
            "| {bins} | {c2c} | {c2n} | {hq} / {mq} | {f1} "
            "| {c1c} / {c1n} |".format(
                rank=i, cell=c["cell"], commit=c["commit"], seed=c["seed"],
                params=nonref, wall=c["wall"], bins=c["n_bins"],
                c2c=c["c2c"], c2n=c["c2n"], hq=c["hq2"], mq=c["mq2"],
                f1=fmt_f1(c["f1"]), c1c=c["c1c"], c1n=c["c1n"],
            )
        )

    table = "\n".join(lines) + "\n"

    meta_note = ""
    flagged = [c for c in cells if c["mismatches"]]
    if flagged:
        meta_note = (
            "\n## Parameter-provenance cross-check\n\n"
            "Parameters are read from each run's `cmd_wrapper:` line — the "
            "record of what COMEBin actually received — not from the driver's "
            "`sweep:` meta line, which went stale for the temperature cells "
            "(the driver was relaunched mid-sweep with a fixed meta writer, but "
            "cells 4–6 had already been launched by the earlier version). "
            "The runs themselves are unaffected: the command line carries "
            "`-l 0.05 / 0.30 / 0.50` and each run log confirms "
            "`Tau(temperature): 0.05 / 0.30 / 0.50`.\n\n"
        )
        for c in flagged:
            meta_note += f"- `{c['cell']}`: {'; '.join(c['mismatches'])}\n"
        meta_note += "\n"

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# Issue #25 sweep — medium-dataset ranking\n\n"
                "Rule: bin stats first (CheckM2 comp/cont + HQ/MQ + F1 = "
                "2·c·p/(c+p), p = 100−cont), then wall time tiebreak. "
                "Only the winning parameter set advances to CAMI II/III "
                "human.\n\n" + table + meta_note)
    print(table)
    if flagged:
        print("parameter-provenance mismatches (cmd_wrapper is authoritative):")
        for c in flagged:
            print(f"  {c['cell']}: {'; '.join(c['mismatches'])}")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()