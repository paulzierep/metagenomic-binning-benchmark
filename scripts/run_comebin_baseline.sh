#!/usr/bin/env bash
# run_comebin_baseline.sh — run UNMODIFIED COMEBin on the demo dataset.
# All inputs/outputs on /vol/data. Prints per-stage timing to stdout + log file.
set -euo pipefail

MM=${MM:-/vol/data/tools/bin/micromamba}
ENV=${ENV:-/vol/data/envs/comebin}
SRC=${SRC_COMEBIN:-/vol/data/repos/COMEBin}
DATA=${DATA:-/vol/data/datasets/comebin_test_data}
CONTIGS=${CONTIGS:-"$DATA/BATS_SAMN07137077_METAG.scaffolds.min500.fasta.f1k.fasta"}
BAMDIR=${BAMDIR:-"$DATA/bamfiles"}
RUNDIR=$(realpath -m "${1:-/vol/data/benchmark/runs/baseline_unmodified}")
THREADS=${THREADS:-32}
BENCH_ROOT=${BENCH_ROOT:-/vol/data/benchmark}
ACTIVE="$BENCH_ROOT/.active_run"
START_LOCK=${BENCHMARK_START_LOCK:-/tmp/benchmark-start.lock}

[ -x "$MM" ] || { echo "ERROR: micromamba is not executable: $MM"; exit 1; }
[ -f "$SRC/COMEBin/run_comebin.sh" ] || { echo "ERROR: invalid SRC_COMEBIN repo root: $SRC"; exit 1; }
[ -f "$CONTIGS" ] || { echo "ERROR: contigs file not found: $CONTIGS"; exit 1; }
[ -d "$BAMDIR" ] || { echo "ERROR: bam directory not found: $BAMDIR"; exit 1; }
[ "$RUNDIR" != "/" ] || { echo "ERROR: refusing rundir=/"; exit 1; }

mkdir -p "$RUNDIR"
RESUME=${BENCHMARK_RESUME:-0}
PH1_WALL=0
if [ "$RESUME" = "1" ]; then
  # Binning-only continuation of a phase-1 run whose wrapper exited 0 but whose
  # clustering produced no bins (upstream run_comebin.sh masks clustering
  # errors; root cause: hmmer 3.4 rejects --cut_tc on the TC-less marker HMM,
  # see PROGRESS.md / issue). Training artifacts are reused as-is; every
  # phase-1 record is archived under logs/phase1/ before the rerun starts.
  [ -f "$RUNDIR/run_meta.txt" ] || { echo "ERROR: BENCHMARK_RESUME=1 but no run_meta.txt in $RUNDIR"; exit 1; }
  grep -q '^exit_code:' "$RUNDIR/run_meta.txt" || { echo "ERROR: BENCHMARK_RESUME=1 but phase 1 recorded no exit_code"; exit 1; }
  n_emb=$(find "$RUNDIR/comebin_out/comebin_res" -maxdepth 1 -type f -name '*embeddings.tsv' 2>/dev/null | wc -l)
  n_aug=$(find "$RUNDIR/comebin_out/data_augmentation" -maxdepth 1 -type f -name '*_datacoverage_mean*' 2>/dev/null | wc -l)
  [ "$n_emb" -eq 2 ] || { echo "ERROR: resume needs exactly 2 embeddings.tsv (found $n_emb); refusing"; exit 1; }
  [ "$n_aug" -eq 6 ] || { echo "ERROR: resume needs 6 augmented views (found $n_aug); refusing"; exit 1; }
  PH1_WALL=$(grep -m1 '^wall_s:' "$RUNDIR/run_meta.txt" | awk '{print $2}')
  case "$PH1_WALL" in ''|*[!0-9]*) PH1_WALL=0 ;; esac
  mkdir -p "$RUNDIR/logs/phase1"
  mv "$RUNDIR/run_meta.txt" "$RUNDIR/logs/phase1/run_meta.txt"
  if [ -f "$RUNDIR/comebin_run.log" ]; then
    mv "$RUNDIR/comebin_run.log" "$RUNDIR/logs/phase1/comebin_run.log"
  fi
  # cluster_res only holds debris from the failed get_result (profile.run dirs
  # for a seed count of 0).  Left in place it would make run_get_final_result
  # skip profiling entirely because it only checks os.path.exists(output_dir).
  if [ -d "$RUNDIR/comebin_out/comebin_res/cluster_res" ]; then
    mv "$RUNDIR/comebin_out/comebin_res/cluster_res" "$RUNDIR/logs/phase1/cluster_res_debris"
  fi
  # A zero-byte hmmsearch output makes upstream gen_seed() skip hmmsearch (it
  # only checks os.path.exists) and the marker script then yields no seed.
  for f in "$CONTIGS.bacar_marker.hmmout" "$CONTIGS.bacar_marker.hmmout.out" "$CONTIGS.bacar_marker.hmmout.err"; do
    if [ -f "$f" ]; then mv "$f" "$RUNDIR/logs/phase1/"; fi
  done
  echo "resume: phase 1 archived to $RUNDIR/logs/phase1/ (phase1_wall_s=$PH1_WALL, embeddings=$n_emb, views=$n_aug)"
elif [ -f "$RUNDIR/run_meta.txt" ] || [ -d "$RUNDIR/comebin_out" ]; then
  echo "ERROR: refusing to overwrite existing run directory: $RUNDIR"
  echo "Choose a fresh rundir (autorestart directories are created by benchmark-watchdog)."
  echo "For a binning-only continuation of a finished phase-1 run: BENCHMARK_RESUME=1 bash run_comebin_baseline.sh $RUNDIR"
  exit 1
fi

COMMIT=$(git -C "$SRC" rev-parse HEAD)
STATUS=$(git -C "$SRC" status --porcelain --untracked-files=all 2>/dev/null || true)
# Python bytecode generated by a prior invocation is not a source edit.  Ignore
# only that well-known cache shape; every tracked or other untracked change is
# still rejected so the baseline remains reproducible.
DIRTY=$(printf '%s\n' "$STATUS" | awk '
  /^\?\? (.*\/)?__pycache__(\/|$)/ {next}
  NF {n++}
  END {print n+0}')
CACHE_ENTRIES=$(printf '%s\n' "$STATUS" | awk '/^\?\? (.*\/)?__pycache__(\/|$)/ {n++} END {print n+0}')
echo "source commit: $COMMIT (dirty files: $DIRTY; ignored __pycache__ entries: $CACHE_ENTRIES)"
[ "$DIRTY" -eq 0 ] || { echo "REFUSING: baseline source is modified; use pristine upstream"; exit 1; }

# Serialize new launches and refuse overlap with the independently tracked run.
# BENCHMARK_WATCHDOG_REPLACE=1 is set only by the watchdog after it has verified
# that the old registered process is gone.
exec 9>"$START_LOCK"
flock -n 9 || { echo "ERROR: another benchmark launch holds $START_LOCK"; exit 1; }
if [ -f "$ACTIVE" ] && [ "${BENCHMARK_WATCHDOG_REPLACE:-0}" != "1" ]; then
  read -r active_pid active_pgid active_log active_dir active_start active_mode active_src < "$ACTIVE" || true
  active_state=$(ps -o stat= -p "${active_pid:-0}" 2>/dev/null | tr -d ' ' || true)
  if [ -n "${active_pid:-}" ] && kill -0 "$active_pid" 2>/dev/null && [[ "$active_state" != Z* ]]; then
    echo "ERROR: benchmark already active: pid=$active_pid dir=$active_dir mode=${active_mode:-baseline}"
    echo "Small functional tests and full benchmarks must never overlap; try again after that run finishes."
    exit 1
  fi
  old_rc=$(grep -m1 '^exit_code:' "${active_dir:-/nonexistent}/run_meta.txt" 2>/dev/null | awk '{print $2}' || true)
  if [ "${old_rc:-}" = "0" ]; then
    echo "clearing completed stale active-run registration for $active_dir"
    rm -f "$ACTIVE"
  else
    echo "ERROR: stale failed active run is registered: pid=$active_pid dir=$active_dir"
    echo "Run /vol/data/benchmark/bin/benchmark-watchdog.sh to triage it; not starting a second run."
    exit 1
  fi
fi

{
  echo "run:        $RUNDIR"
  echo "date:       $(date -Is)"
  echo "source:     $SRC"
  echo "commit:     $COMMIT"
  echo "contigs:    $CONTIGS"
  echo "bamdir:     $BAMDIR"
  echo "threads:    $THREADS"
  echo "host:       $(nproc) cores, $(free -g | awk '/Mem:/{print $2}')G RAM, gpu=$(nvidia-smi -L 2>/dev/null || echo none)"
  echo "cmd_wrapper: bash run_comebin.sh -a $CONTIGS -p $BAMDIR -o $RUNDIR/comebin_out -n 6 -t $THREADS  # via: micromamba run -p $ENV"
  echo "hmmsearch:  $("$ENV/bin/hmmsearch" -h 2>&1 | grep -m1 HMMER || echo unknown)"
  if [ "$RESUME" = "1" ]; then
    echo "resume:     binning-only continuation; phase-1 records archived under logs/phase1/ (phase1_wall_s=$PH1_WALL)"
  fi
} | tee "$RUNDIR/run_meta.txt"

export MAMBA_ROOT_PREFIX=/vol/data/envs/.mamba
# Do not leave new bytecode caches in the pristine source tree.  The source
# check above also tolerates old caches from historical runs.
export PYTHONDONTWRITEBYTECODE=1
export PYTHONUNBUFFERED=1
cd "$SRC/COMEBin"   # upstream resolves ../auxiliary relative to CWD

# Register this run for the benchmark watchdog (scripts/benchmark-watchdog.sh).
# Fields: pid pgid logfile rundir start_epoch mode source_repo.
printf '%s %s %s %s %s %s %s\n' "$$" "$(ps -o pgid= -p $$ | tr -d ' ')" \
  "$RUNDIR/comebin_run.log" "$RUNDIR" "$(date +%s)" baseline "$SRC" > "$ACTIVE.tmp.$$"
mv "$ACTIVE.tmp.$$" "$ACTIVE"

START=$(date +%s)
TERMINAL=0
write_terminal() {
  local rc=$1 end=$2
  [ "$TERMINAL" -eq 1 ] && return 0
  {
    echo "exit_code:  $rc"
    # For a resumed run wall_s is the end-to-end cost: archived phase 1 + this
    # phase. phase2_wall_s keeps the continuation's own duration visible.
    echo "wall_s:     $((end-START+PH1_WALL))"
    if [ "$PH1_WALL" -gt 0 ] 2>/dev/null; then
      echo "phase2_wall_s: $((end-START))"
    fi
    echo "finished:   $(date -Is)"
    echo "terminal:   wrapper_exit"
  } | tee -a "$RUNDIR/run_meta.txt" || true
  TERMINAL=1
}

cleanup() {
  local rc=$?
  trap - EXIT
  if [ "$TERMINAL" -eq 0 ]; then
    set +e
    write_terminal "$rc" "$(date +%s)"
    set -e
  fi
  # A failed run remains registered so benchmark-watchdog can classify it.  Only
  # a successful run clears its own registration.
  if [ "$rc" -eq 0 ] && [ -f "$ACTIVE" ]; then
    read -r current_pid _ < "$ACTIVE" || true
    [ "${current_pid:-}" = "$$" ] && rm -f "$ACTIVE"
  fi
  exit "$rc"
}
trap cleanup EXIT
trap 'exit 143' TERM
trap 'exit 130' INT

# Capture the real main.py train command once training starts (non-blocking).
( sleep 12; MCMD=$(pgrep -af 'main.py train' 2>/dev/null | head -1 | cut -d' ' -f2-); \
  [ -n "$MCMD" ] && echo "cmd_train_py: $MCMD" >> "$RUNDIR/run_meta.txt" ) &

set +e
CUDA_VISIBLE_DEVICES= "$MM" run -p "$ENV" bash run_comebin.sh \
  -a "$CONTIGS" -p "$BAMDIR" -o "$RUNDIR/comebin_out" \
  -n 6 -t "$THREADS" 2>&1 | tee "$RUNDIR/comebin_run.log"
RC=${PIPESTATUS[0]}
set -e
END=$(date +%s)

# The upstream wrapper only checks get_result's exit code, and get_result can
# fail without propagating it (phase 1 recorded exit_code 0 with zero bins).
# Never let run_meta claim success when no bins were produced.
BINS="$RUNDIR/comebin_out/comebin_res/comebin_res_bins"
BIN_COUNT=0
if [ -d "$BINS" ]; then
  BIN_COUNT=$(find -L "$BINS" -maxdepth 1 -type f -size +0c | wc -l)
fi
if [ "$RC" -eq 0 ] && [ "$BIN_COUNT" -eq 0 ]; then
  echo "bins_missing: wrapper exited 0 but $BINS holds no bin files; recording failure" \
    | tee -a "$RUNDIR/run_meta.txt"
  RC=1
fi
write_terminal "$RC" "$END"
if [ "$BIN_COUNT" -gt 0 ]; then
  echo "bins: $BIN_COUNT  -> $BINS" | tee -a "$RUNDIR/run_meta.txt"
fi
# Record helper-tool commands visible in the log (FragGeneScan/hmmsearch seed genes).
grep -aE 'run_FragGeneScan|hmmsearch' "$RUNDIR/comebin_run.log" 2>/dev/null | head -2 \
  | sed 's/^/cmd_from_log: /' | tee -a "$RUNDIR/run_meta.txt" >/dev/null || true
exit "$RC"
